import { Pool, type PoolConfig } from "pg";
import { attachDatabasePool } from "@vercel/functions";
import { MEDIC_PHOTOS } from "./medic-photos";
import { seed } from "./seed";
import { queryAll, queryOne, type Queryable } from "./sql";

type GlobalDb = {
  verbaPool?: Pool;
  verbaReady?: Promise<void>;
};

const globalDb = globalThis as unknown as GlobalDb;

function redact(text: string): string {
  return text.replace(/postgres(?:ql)?:\/\/\S+/gi, "[redacted-url]");
}

function pooledUrl(): string {
  const value = process.env.DATABASE_URL?.trim();
  if (!value) throw new Error("Нет DATABASE_URL. Нужна pooled-строка Neon Postgres.");
  return value;
}

function directUrl(): string {
  const value = process.env.DATABASE_URL_UNPOOLED?.trim();
  if (value) return value;
  const url = new URL(pooledUrl());
  url.hostname = url.hostname.replace("-pooler", "");
  return url.toString();
}

function poolConfig(connectionString: string): PoolConfig {
  return {
    connectionString,
    max: process.env.VERCEL ? 5 : 10,
    idleTimeoutMillis: 5_000,
  };
}

async function migrate(db: Queryable) {
  await db.query(`
    CREATE TABLE IF NOT EXISTS medics (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      specialty TEXT NOT NULL,
      slot_minutes INTEGER NOT NULL,
      active INTEGER NOT NULL DEFAULT 1,
      photo TEXT
    );

    CREATE TABLE IF NOT EXISTS schedules (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      medic_id INTEGER NOT NULL REFERENCES medics(id) ON DELETE CASCADE,
      weekday INTEGER NOT NULL,
      start_time TEXT NOT NULL,
      end_time TEXT NOT NULL,
      UNIQUE (medic_id, weekday)
    );

    CREATE TABLE IF NOT EXISTS appointments (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      medic_id INTEGER NOT NULL REFERENCES medics(id),
      date TEXT NOT NULL,
      time TEXT NOT NULL,
      client_name TEXT NOT NULL,
      client_phone TEXT NOT NULL,
      source TEXT NOT NULL CHECK (source IN ('site', 'telegram')),
      telegram_user_id TEXT,
      status TEXT NOT NULL DEFAULT 'booked' CHECK (status IN ('booked', 'cancelled')),
      created_at TEXT NOT NULL
    );

    CREATE UNIQUE INDEX IF NOT EXISTS appointments_slot_active
      ON appointments (medic_id, date, time)
      WHERE status = 'booked';

    ALTER TABLE appointments ADD COLUMN IF NOT EXISTS reminder_hour_sent INTEGER NOT NULL DEFAULT 0;
    ALTER TABLE appointments ADD COLUMN IF NOT EXISTS reminder_soon_sent INTEGER NOT NULL DEFAULT 0;
    ALTER TABLE appointments ADD COLUMN IF NOT EXISTS reminder_hour_tries INTEGER NOT NULL DEFAULT 0;
    ALTER TABLE appointments ADD COLUMN IF NOT EXISTS reminder_soon_tries INTEGER NOT NULL DEFAULT 0;

    ALTER TABLE medics ADD COLUMN IF NOT EXISTS photo TEXT;

    CREATE TABLE IF NOT EXISTS bot_sessions (
      key TEXT PRIMARY KEY,
      value JSONB NOT NULL,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);
  await db.query(`
    UPDATE appointments
    SET client_phone = '+998' || substr(client_phone, 3, 9)
    WHERE client_phone LIKE '+7%';
  `);
  await seed(db);
  for (const [name, photo] of Object.entries(MEDIC_PHOTOS)) {
    await db.query("UPDATE medics SET photo = $1 WHERE name = $2 AND (photo IS NULL OR photo = '')", [photo, name]);
  }
}

async function ensureReady(): Promise<void> {
  if (!globalDb.verbaReady) {
    globalDb.verbaReady = (async () => {
      const { Client } = await import("pg");
      const client = new Client(poolConfig(directUrl()));
      await client.connect();
      try {
        await migrate(client);
      } finally {
        await client.end();
      }
    })().catch((error: unknown) => {
      globalDb.verbaReady = undefined;
      const message = error instanceof Error ? error.message : String(error);
      throw new Error(redact(message));
    });
  }
  return globalDb.verbaReady;
}

async function getPool(): Promise<Pool> {
  await ensureReady();
  if (!globalDb.verbaPool) {
    const pool = new Pool(poolConfig(pooledUrl()));
    attachDatabasePool(pool);
    globalDb.verbaPool = pool;
  }
  return globalDb.verbaPool;
}

export async function all<T extends Record<string, unknown>>(sql: string, params: unknown[] = []): Promise<T[]> {
  return queryAll<T>(await getPool(), sql, params);
}

export async function one<T extends Record<string, unknown>>(
  sql: string,
  params: unknown[] = [],
): Promise<T | undefined> {
  return queryOne<T>(await getPool(), sql, params);
}

export async function tx<T>(fn: (db: Queryable) => Promise<T>): Promise<T> {
  const pool = await getPool();
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    const result = await fn(client);
    await client.query("COMMIT");
    return result;
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}

export function isUniqueViolation(error: unknown): boolean {
  return typeof error === "object" && error !== null && "code" in error && (error as { code: unknown }).code === "23505";
}
